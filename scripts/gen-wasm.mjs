// Assemble src/engine/wasm/*.wat into TypeScript modules holding the binary as base64 (so the single-file
// build and file:// pages need no extra fetch). Run with `npm run wasm` after editing a .wat file.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import wabtInit from "wabt";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/engine/wasm");
const wabt = await wabtInit();
for (const name of fs.readdirSync(dir).filter((f) => f.endsWith(".wat"))) {
  const src = fs.readFileSync(path.join(dir, name), "utf8");
  const mod = wabt.parseWat(name, src, { simd: true });
  mod.validate();
  const { buffer } = mod.toBinary({ log: false, write_debug_names: false });
  mod.destroy();
  const b64 = Buffer.from(buffer).toString("base64");
  const base = name.replace(/\.wat$/, "");
  const out = path.join(dir, `${base}Binary.ts`);
  fs.writeFileSync(out, `// Generated by scripts/gen-wasm.mjs from ${name} (${buffer.length} bytes). Do not edit.\nexport const ${base.toUpperCase()}_WASM = "${b64}";\n`);
  console.log(`${path.relative(root, out)}: ${buffer.length} bytes`);
}
