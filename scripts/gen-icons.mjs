// Generates src/ui/codicons.ts: the subset of VS Code Codicons the UI uses, inlined as SVG strings
// (no icon font, no network: the app also ships as one self-contained HTML file).
// Usage: npm run icons    (reads node_modules/@vscode/codicons/src/icons/*.svg)
// Codicons © Microsoft Corporation, licensed under CC BY 4.0 — https://github.com/microsoft/vscode-codicons
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("@vscode/codicons/package.json"));
const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));

/** Codicons used by src/ui/icons.ts. */
const NAMES = [
  "new-file", "folder-opened", "save", "device-camera-video", "info", "file-binary", "output", "discard", "redo",
  "settings-gear", "sparkle", "screen-full", "cursor", "zoom-in", "graph", "clockface", "graph-line", "settings",
  "play", "debug-pause", "debug-stop", "debug-continue", "debug-reverse-continue", "device-camera", "export",
  "bookmark", "debug-restart", "unmute", "mute", "sync", "close", "link", "file-media", "chevron-down",
  "chevron-right", "check", "arrow-swap", "question", "arrow-left", "arrow-right", "edit", "trash", "add", "remove",
  "chrome-minimize", "chrome-maximize", "ellipsis", "send", "loading",
];

const read = (name) => readFileSync(join(pkgDir, "src", "icons", `${name}.svg`), "utf8");
/** Inner markup of a Codicon (its <path> elements), with whitespace normalized. */
function inner(name) {
  const m = /<svg[^>]*>([\s\S]*?)<\/svg>/.exec(read(name));
  if (!m) throw new Error(`Unexpected SVG markup in ${name}.svg`);
  return m[1].replace(/\s+/g, " ").replace(/>\s+</g, "><").trim();
}
const wrap = (body) => `<svg viewBox="0 0 16 16" fill="currentColor" aria-hidden="true">${body}</svg>`;

/** Splits the single path of a step glyph into its triangle (outer + inner contour) and its bar. */
function stepParts(name) {
  const d = /<path d="([^"]+)"/.exec(inner(name))?.[1];
  const sub = d?.split(/(?=M)/) ?? [];
  if (sub.length !== 3) throw new Error(`${name}: expected 3 subpaths, got ${sub.length}`);
  return { tri: sub[0] + sub[1], bar: sub[2] };
}

const out = {};
for (const n of NAMES) out[n] = wrap(inner(n));
// Media transport glyphs Codicons lacks, assembled from its own step glyphs (same geometry and weight):
// first frame |◁ = the triangle of debug-reverse-continue (◁|) with its bar moved to the left;
// last frame ▷| = the triangle of debug-continue (|▷) with its bar moved to the right.
{
  const r = stepParts("debug-reverse-continue"), c = stepParts("debug-continue");
  out["x-first-frame"] = wrap(`<path transform="translate(4 0)" d="${r.tri}"/><path transform="translate(-10.5 0)" d="${r.bar}"/>`);
  out["x-last-frame"] = wrap(`<path transform="translate(-4 0)" d="${c.tri}"/><path transform="translate(10.5 0)" d="${c.bar}"/>`);
}

const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
const ts = `// GENERATED by scripts/gen-icons.mjs from @vscode/codicons ${pkg.version} — do not edit by hand.
// Codicons © Microsoft Corporation, licensed under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
// Source: https://github.com/microsoft/vscode-codicons — "x-" glyphs are rearranged from Codicon paths.
export const CODICONS = {
${body}
} as const;

export type CodiconName = keyof typeof CODICONS;
`;
writeFileSync(join(root, "src", "ui", "codicons.ts"), ts);
console.log(`src/ui/codicons.ts: ${Object.keys(out).length} glyphs (${(ts.length / 1024).toFixed(1)} KB) from @vscode/codicons ${pkg.version}`);
