#!/usr/bin/env python3
"""Generate the built-in bitmap font used by the native rasterizer.

The Android app has no canvas and no bundled font file, so the annotation text is drawn with a small
bitmap font embedded in the app. The glyphs are rendered once from DejaVu Sans Mono (the reference
monospace face of the workbench) and stored as a bit table, so every device draws the same labels.

Usage:  python3 scripts/gen_bitmap_font.py > lib/engine/kernels/font.ts

Requires ImageMagick (`convert`) and DejaVu Sans Mono. The generated file is committed, so the build
never needs ImageMagick.
"""
import subprocess
import sys

CELL_W = 8
CELL_H = 13
POINT_SIZE = 12
FONT = "DejaVu-Sans-Mono"


def render(ch: str) -> bytes:
    """One glyph as CELL_H rows of CELL_W pixels (1 = ink)."""
    if ch == " ":
        return bytes(CELL_W * CELL_H)
    # ImageMagick's label: protocol treats "\\" as an escape character, so it has to be doubled.
    label = ch.replace("\\", "\\\\")
    cmd = [
        "convert", "-background", "black", "-fill", "white",
        "-font", FONT, "-pointsize", str(POINT_SIZE),
        "-gravity", "center", "-extent", f"{CELL_W}x{CELL_H}",
        f"label:{label}", "-depth", "8", "gray:-",
    ]
    out = subprocess.run(cmd, capture_output=True, check=True).stdout
    if len(out) != CELL_W * CELL_H:
        raise SystemExit(f"unexpected glyph size for {ch!r}: {len(out)}")
    return bytes(1 if v > 110 else 0 for v in out)


def main() -> None:
    glyphs = bytearray()
    for code in range(32, 127):
        glyphs += render(chr(code))
    hex_data = glyphs.hex()
    lines = [hex_data[i:i + 96] for i in range(0, len(hex_data), 96)]
    body = "\n".join(f'  "{l}"' for l in lines)
    print(f"""// Built-in bitmap font (generated by scripts/gen_bitmap_font.py from DejaVu Sans Mono).
//
// One byte per pixel, row major, {CELL_W}x{CELL_H} cells for the printable ASCII range (32..126).
// The native rasterizer draws annotation text with this font, so a label looks the same on every
// device and in every exported frame.

export const FONT_CELL_W = {CELL_W};
export const FONT_CELL_H = {CELL_H};

const HEX =
{body};

const BYTES = new Uint8Array((HEX.length >> 1));
for (let i = 0; i < BYTES.length; i++) BYTES[i] = parseInt(HEX.substr(i * 2, 2), 16);

/** Glyph bitmaps, row major, {CELL_W}x{CELL_H} pixels per glyph (ASCII 32..126). */
export const FONT_DATA = BYTES;

/** Nominal font size of the embedded face (pixels). */
export const fontSize = () => {{
  return FONT_CELL_H;
}};
""")


if __name__ == "__main__":
    main()
